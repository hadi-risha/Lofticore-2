// Stand-in 3D models so the AR view can be tried. They are Khronos's public sample
// assets, loaded from their site rather than copied here. Real products need models
// made for them - sellers upload their own .glb files in the product form.
const KHRONOS = "https://raw.githubusercontent.com/KhronosGroup/glTF-Sample-Assets/main/Models";
export const sampleModels = {
  chair: `${KHRONOS}/SheenChair/glTF-Binary/SheenChair.glb`,
  sofa: `${KHRONOS}/GlamVelvetSofa/glTF-Binary/GlamVelvetSofa.glb`,
  diningChair: `${KHRONOS}/ChairDamaskPurplegold/glTF-Binary/ChairDamaskPurplegold.glb`,
};

export function sampleModelFor(title: string): string | undefined {
  const t = title.toLowerCase();
  if (/dining set/.test(t)) return sampleModels.diningChair;
  if (/sofa|daybed/.test(t)) return sampleModels.sofa;
  if (/chair|lounger|papasan/.test(t)) return sampleModels.chair;
  return undefined;
}
